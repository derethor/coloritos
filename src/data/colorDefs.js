export function tailwindRamp(name) {
  return TW_DATA[name].split(';').map((entry) => {
    const [L, C, H] = entry.split(',').map(Number);
    return [L / 1000, C / 1000, H / 1000];
  });
}

export function makeBand(name) {
  const ramp = tailwindRamp(name);
  const H = ramp.map((point) => point[2]);
  const L = ramp.map((point) => point[0]);
  const C = ramp.map((point) => point[1]);
  const hue = H[5];
  return {
    name,
    hue,
    H,
    L,
    C,
    locked: false,
    default: { hue, H: H.slice(), L: L.slice(), C: C.slice() },
  };
}

export function makeInitialBands() {
  return COLOR_DEFS.map((def) => makeBand(...def));
}
